#!/usr/bin/env python3
"""Generates Packages/DelosKit/Sources/DelosUI/Symbols.swift from DELOS for Android's generated Symbols.kt.

    python3 tools/fonts/sync_symbols.py /path/to/DELOS          # the Android checkout

The icon fonts (phosphor_regular.ttf, phosphor_fill.ttf) are the Android subsets, copied byte for byte (checksums in
docs/THIRD_PARTY.md); the code points come from the same build, so both stay in step when they are copied together.
Standard library only.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "Packages/DelosKit/Sources/DelosUI/Symbols.swift"
SOURCE = "app/src/main/java/com/limelight/shell/ui/Symbols.kt"
CONST = re.compile(r'^\s*const val ([A-Z0-9_]+) = "\\u([0-9A-F]{4})"')


SWIFT_KEYWORDS = set("""associatedtype class deinit enum extension fileprivate func import init inout internal let open
operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue
default defer do else fallthrough for guard if in repeat return throw switch where while as false is nil self super throws
true try any some""".split())


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    ident = head + "".join(w.capitalize() for w in rest)
    return f"`{ident}`" if ident in SWIFT_KEYWORDS else ident


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    android = Path(sys.argv[1])
    kt = (android / SOURCE).read_text(encoding="utf-8")
    commit = subprocess.run(["git", "-C", str(android), "log", "-1", "--format=%h", "--", SOURCE],
                            capture_output=True, text=True, check=True).stdout.strip()
    rows = [(camel(m.group(1)), m.group(2)) for line in kt.splitlines() if (m := CONST.match(line))]
    if not rows:
        print("no symbols found", file=sys.stderr)
        return 1
    lines = [
        "// Generated by tools/fonts/sync_symbols.py from DELOS for Android's Symbols.kt "
        f"(commit {commit}) - do not edit by hand.",
        "",
        "/// Phosphor 2.1.2 code points shared by the bundled Regular and Fill subsets.",
        "public enum Symbols {",
    ]
    lines += [f'    public static let {name} = "\\u{{{code}}}"' for name, code in rows]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} symbols")
    return 0


if __name__ == "__main__":
    sys.exit(main())
